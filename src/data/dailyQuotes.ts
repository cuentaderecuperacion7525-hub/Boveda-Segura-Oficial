/**
 * Devuelve la reflexión diaria correspondiente al mes y día del calendario actual,
 * completamente independiente del año (los 365 días normales + 29 de febrero tienen
 * siempre su propia frase única sin desplazamientos en años bisiestos).
 */
export function getDailyReflection(date: Date = new Date()): string {
  const month = date.getMonth(); // 0 - 11
  const day = date.getDate(); // 1 - 31
  const offset = MONTH_DAY_OFFSETS[month] ?? 0;
  const index = (offset + Math.max(0, day - 1)) % DAILY_QUOTES.length;
  return DAILY_QUOTES[index] || DAILY_QUOTES[0];
}
